const WEIGHT_TIERS = [
  { maxKg: 1, cents: { A: 450, B: 550, C: 700 } },
  { maxKg: 5, cents: { A: 900, B: 1100, C: 1400 } },
  { maxKg: 20, cents: { A: 1800, B: 2200, C: 2900 } },
];

const REMOTE_SURCHARGE_CENTS = 500;

function findArea(postalCode) {
  const area = AREAS.find((candidate) => candidate.prefix === String(postalCode).slice(0, 3));
  if (!area) throw new RangeError(`Unknown postal code ${postalCode}`);
  return area;
}

/**
 * Shipping cost in cents. A tier covers parcels up to and including its
 * maxKg; remote areas pay a surcharge.
 */
function shippingCost(postalCode, weightKg) {
  if (!(weightKg > 0)) throw new RangeError("weightKg must be positive");
  const area = findArea(postalCode);
  const tier = WEIGHT_TIERS.find((candidate) => weightKg < candidate.maxKg);
  if (!tier) throw new RangeError("Parcel is too heavy to ship");
  return tier.cents[area.zone] + (area.remote ? REMOTE_SURCHARGE_CENTS : 0);
}

module.exports = { AREAS, findArea, shippingCost };
